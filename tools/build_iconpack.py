#!/usr/bin/env python3
"""app/public/iconpack/*.png|jpg|webp -> app/src/config/iconpack.ts. A file is matched to an app by its name, ignoring case and
anything that isn't a letter or digit: netflix.png, Prime-Video.png, com.apple.appletv.png, jiohotstar.png ... match the
app's id or its title (see config/catalog.ts and the names the launcher shows)."""
import os, re
ROOT = os.path.abspath(os.environ.get('LUMEN_APP', os.path.join(os.path.dirname(__file__), '../app')))
d = f'{ROOT}/public/iconpack'
files = sorted(f for f in os.listdir(d) if re.search(r'\.(png|jpe?g|webp)$', f, re.I)) if os.path.isdir(d) else []
slug = lambda s: re.sub(r'[^a-z0-9]+', '', s.lower())
rows = ",\n".join(f"\t'{slug(os.path.splitext(f)[0])}': '{f}'" for f in files)
os.makedirs(f'{ROOT}/src/config', exist_ok=True)
open(f'{ROOT}/src/config/iconpack.ts', 'w').write(
 "// Generated by tools/build_iconpack.py from public/iconpack/ - do not edit by hand.\n"
 "// Key: the file name without extension, lower-case letters and digits only. Value: the file.\n"
 "export const ICON_PACK: Record<string, string> = {\n" + rows + "\n};\n")
print(len(files), 'icon pack files')
