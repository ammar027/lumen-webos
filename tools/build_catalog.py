#!/usr/bin/env python3
"""tools/catalog.json (from harvest.py and harvest_open.py) + the bundled defaults (tools/defaults.json) -> app/src/config/wallpapers.ts.
The bundled defaults come from tools/defaults.json (files in app/public/wallpapers/). The Art and Landscapes pictures and the url/credit shorthand
are from Sam Renfrew's fork (MIT)."""
import json, os, re, glob
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cat = json.load(open(f'{ROOT}/tools/catalog.json'))
CAP = 60
def clean(t):
    t = re.sub(r'\[[^\]]*\]|\([^)]*\d{3,4}\s*[x×]\s*\d{3,4}[^)]*\)', ' ', t)      # [OC] [3840x2160] (4000x3000)
    t = re.sub(r'\s+', ' ', t).strip(' -–—,.:;|')
    if len(t) > CAP: t = t[:CAP].rsplit(' ', 1)[0].rstrip(' ,.-') + '…'
    return t or 'Untitled'
cats = []
rows = []
WIKI = re.compile(r'^https://thumb\.wikimedia\.org/wikipedia/commons/thumb/([0-9a-f]/[0-9a-f]{2})/([^/]+)/1920px-\2$')
CMA = re.compile(r'^https://openaccess-cdn\.clevelandart\.org/([^/]+)/\1_print\.jpg$')
FIRST = ['Landscapes', 'Art']      # the picker lists these two first, in this order
for c in cat:
    ext = c['url'].rsplit('.', 1)[1]
    row = {'id': c['id'], 'e': 'j' if ext.startswith('jp') else 'p', 't': clean(c['title']), 'c': c['category']}
    if c['url'].startswith('https://i.redd.it/'): row['u'] = ''        # a Reddit picture is rebuilt from its id and ext
    elif WIKI.match(c['url']): row['u'] = 'w:' + '/'.join(WIKI.match(c['url']).groups())   # the URL repeats the file name: keep it once
    elif CMA.match(c['url']): row['u'] = 'c:' + CMA.match(c['url']).group(1)
    else: row['u'] = c['url'][len('https://'):]                          # anything else keeps its URL (no scheme: it is the same in every one)
    if c.get('credit'): row['r'] = c['credit']
    rows.append(row)
    if c['category'] not in cats: cats.append(c['category'])
cats = [c for c in FIRST if c in cats] + [c for c in cats if c not in FIRST]
defaults = json.load(open(f'{ROOT}/tools/defaults.json')) if os.path.exists(f'{ROOT}/tools/defaults.json') else []
ts = ["// Generated by tools/build_catalog.py - do not edit by hand.",
      "// The wallpaper library. Cloud pictures (Reddit's image host, Met, Cleveland, Wikimedia Commons) are loaded only when you pick them;",
      "// the bundled defaults (public/wallpapers/default-N.jpg, or your own from app/private/) are always available offline.", "",
      "export interface Wallpaper { id: string; ext: 'j' | 'p'; title: string; category: string; url?: string; credit?: string }",
      "export interface LocalWallpaper { title: string; file: string }", "",
      "export const WALLPAPER_CATEGORIES: string[] = " + json.dumps(cats) + ";", "",
      "export const LOCAL_WALLPAPERS: LocalWallpaper[] = " + json.dumps([{'title': d['title'], 'file': d['file']} for d in defaults], ensure_ascii=False, indent=1) + ";", "",
      "/** url is short for the two big sources: w:<hash path>/<file> is Commons' 1920-wide copy, c:<accession> is Cleveland's print size */",
      "export function cloudUrl (w: Wallpaper): string {",
      "\tconst u = w.url;",
      "\tif (!u) return `https://i.redd.it/${w.id}.${w.ext === 'j' ? 'jpeg' : 'png'}`;",
      "\tif (u.indexOf('w:') === 0) { const file = u.slice(u.lastIndexOf('/') + 1); return `https://thumb.wikimedia.org/wikipedia/commons/thumb/${u.slice(2)}/1920px-${file}`; }",
      "\tif (u.indexOf('c:') === 0) return `https://openaccess-cdn.clevelandart.org/${u.slice(2)}/${u.slice(2)}_print.jpg`;",
      "\treturn 'https://' + u;", "}", "",
      "export const WALLPAPERS: Wallpaper[] = [",
      ",\n".join("\t{id: %s, ext: %s, title: %s, category: %s%s%s}" % (json.dumps(r['id']), json.dumps(r['e']), json.dumps(r['t'], ensure_ascii=False), json.dumps(r['c']),
                  ', url: ' + json.dumps(r['u']) if r['u'] else '', ', credit: ' + json.dumps(r['r'], ensure_ascii=False) if 'r' in r else '') for r in rows),
      "];", ""]
open(f'{ROOT}/app/src/config/wallpapers.ts', 'w').write("\n".join(ts))
print(len(rows), 'cloud wallpapers,', len(defaults), 'local defaults, categories:', cats)
